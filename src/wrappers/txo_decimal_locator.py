"""Frozen decimal locator and tick for the TAIFEX TXO (臺指選) root.

``docs/pages/txo.md`` §2.2 in the taiwan_dashboard monorepo deliberately
does not join Channel 4 (the options I010 feed), so this root's
``DECIMAL-LOCATOR`` is calibrated offline instead, the same way
``ssf_decimal_locator.py`` calibrates the SSF roots, and regenerated by
``scripts/calibrate_txo_locator.py``:

    Fetch https://openapi.taifex.com.tw/v1/DailyMarketReportOpt for a trading
    day, keep TradingSession == '一般' and Contract == 'TXO' rows whose
    ContractMonth(Week) is a plain 6-digit YYYYMM (monthly contract; see
    ``taifex_option_prod_id`` below), derive each row's PROD-ID, join to
    /mnt/nfs/backup/fop_parquets/options_day_<YYYYMMDD>_0840_i024.parquet on
    that PROD-ID, and print round(log10(Close / max(price_raw))) alongside
    the gcd of its consecutive distinct price_raw values.

Only plain monthly contracts are joined. TXO's weekly contracts
(``ContractMonth(Week)`` carrying a ``W``/``F`` suffix in the report) are
*not* reconstructed: checking every distinct prod_id observed with root
``TXO`` in a real day's i024 feed (2026-10-07) against every monthly
contract this module can reconstruct from that same day's report found an
exact match -- all 514 traded monthly contracts, zero unexplained leftovers
either way -- which means TXO's weeklies are carried under a different
PROD-ID root entirely in the raw feed (not identified here; out of scope,
since the root's one locator is already fully evidenced by the monthly
contracts alone).

There is exactly one root today (``TXO``); the table is still keyed by root,
and still versioned/frozen the same way as ``ssf_decimal_locator_table.py``,
in case a second root (e.g. a weekly-options root, once identified) is ever
added.

Money stays integral: ``tick_1e4`` is in 1/10000 NTD (see
``ssf_decimal_locator.price_raw_to_1e4``, reused here unchanged).
"""

import math
from typing import Dict, NamedTuple, Optional

import polars as pl

from .ssf_decimal_locator import _gcd_of, observed_ticks, price_raw_to_1e4
from .txo_decimal_locator_table import (
    TXO_DECIMAL_LOCATOR_CALIBRATION_DAY,
    TXO_DECIMAL_LOCATOR_TABLE,
    TXO_DECIMAL_LOCATOR_VERSION,
)

TXO_DECIMAL_LOCATOR_QUERY = (
    "Fetch https://openapi.taifex.com.tw/v1/DailyMarketReportOpt for a trading day, "
    "keep TradingSession == '一般' and Contract == 'TXO' rows whose "
    "ContractMonth(Week) is a plain 6-digit YYYYMM, derive each row's PROD-ID "
    "(root + strike digits + a month letter, A-L for 買權 / M-X for 賣權 + the "
    "year's last digit), join to "
    "/mnt/nfs/backup/fop_parquets/options_day_<YYYYMMDD>_0840_i024.parquet on "
    "that PROD-ID, and print round(log10(Close / max(price_raw))) alongside the "
    "gcd of its consecutive distinct price_raw values."
)

# Real-world TAIFEX option PROD-ID convention: calls use A-L (Jan..Dec), puts
# use M-X (Jan..Dec) -- confirmed directly against the raw i024 feed (see
# module docstring): every TXO-rooted prod_id observed on 2026-10-07 decodes
# cleanly under exactly this scheme and no other.
CALL_MONTH_CODES = "ABCDEFGHIJKL"
PUT_MONTH_CODES = "MNOPQRSTUVWX"


class TxoLocatorEntry(NamedTuple):
    root: str
    locator: int             # price = price_raw / 10**locator
    tick_raw: Optional[int]  # gcd of observed price steps in price_raw units; None if unobserved
    tick_1e4: Optional[int]  # the same step in 1/10000 NTD
    n_products: int          # distinct monthly contracts the entry aggregates
    n_steps: int             # price changes the gcd was taken over (few = weak evidence)


def taifex_option_prod_id(contract: str, contract_month: str, strike, call_put: str) -> Optional[str]:
    """PROD-ID for one plain-monthly ``DailyMarketReportOpt`` row, or None.

    ``contract_month`` must be a bare ``YYYYMM`` (a monthly contract); a
    weekly contract's month field carries a ``W``/``F`` suffix and returns
    None (see module docstring -- weeklies are out of scope here, carried
    under a different root in the raw feed). ``strike`` is the report's own
    ``StrikePrice`` (a numeric string, no decimal point for TXO); embedded
    in the PROD-ID as a literal integer, exactly as TAIFEX publishes it in
    the raw feed. ``call_put`` is the report's own ``CallPut`` (``買權`` /
    ``賣權``).
    """
    if "/" in contract_month or len(contract_month) != 6 or not contract_month.isdigit():
        return None
    month = int(contract_month[4:6])
    if not 1 <= month <= 12:
        return None
    year_digit = contract_month[3]
    codes = CALL_MONTH_CODES if call_put == "買權" else PUT_MONTH_CODES
    try:
        strike_int = int(float(strike))
    except (TypeError, ValueError):
        return None
    return f"{contract}{strike_int}{codes[month - 1]}{year_digit}"


def get_txo_decimal_locator(prod_id_or_root: str) -> Optional[TxoLocatorEntry]:
    """Frozen entry for a PROD-ID (``TXO24000J6``) or root (``TXO``); None if absent."""
    entry = TXO_DECIMAL_LOCATOR_TABLE.get(prod_id_or_root[:3])
    if entry is None:
        return None
    return TxoLocatorEntry(*entry)


def txo_decimal_locator_version() -> str:
    return TXO_DECIMAL_LOCATOR_VERSION


def txo_decimal_locator_calibration_day() -> str:
    return TXO_DECIMAL_LOCATOR_CALIBRATION_DAY


# ----------------------------------------------------------------------
# Calibration (the query above as code; used by scripts/calibrate_txo_locator.py)
# ----------------------------------------------------------------------

def calibrate_locator(report, i024: pl.LazyFrame) -> pl.DataFrame:
    """One row per TXO plain-monthly contract traded on the calibration day.

    ``report`` is ``TaifexWrapper.get_daily_market_report_opt(day)`` (pandas,
    already ``一般``-session only); ``i024`` the day's options i024 scan.
    Columns: prod_id, strike, call_put, close, max_price_raw, locator,
    tick_raw, n_steps.
    """
    rep = report[report["Contract"] == "TXO"].copy()
    rep["prod_id"] = [
        taifex_option_prod_id("TXO", month, strike, call_put)
        for month, strike, call_put in zip(
            rep["ContractMonth(Week)"], rep["StrikePrice"], rep["CallPut"]
        )
    ]
    rep = rep.dropna(subset=["prod_id"]).drop_duplicates(subset=["prod_id"], keep="first")
    rep_pl = pl.from_pandas(
        rep[["prod_id", "StrikePrice", "CallPut", "Close"]].rename(
            columns={"StrikePrice": "strike", "CallPut": "call_put", "Close": "close"}
        )
    )

    joined = observed_ticks(
        i024.filter(pl.col("prod_id").str.starts_with("TXO"))
    ).join(rep_pl, on="prod_id", how="inner")

    def locator_of(close: str, max_raw: int) -> Optional[int]:
        try:
            value = float(close)
        except (TypeError, ValueError):
            return None
        if value <= 0 or max_raw <= 0:
            return None
        return -round(math.log10(value / max_raw))

    locators = [locator_of(c, m) for c, m in zip(joined["close"], joined["max_price_raw"])]
    out = joined.with_columns(pl.Series("locator", locators, dtype=pl.Int64))
    return out.select(
        "prod_id", "strike", "call_put", "close", "max_price_raw",
        "locator", "tick_raw", "n_steps",
    ).sort("prod_id")


def disagreements(calibrated: pl.DataFrame) -> pl.DataFrame:
    """Contracts whose locator differs from the root's most common locator."""
    valid = calibrated.filter(pl.col("locator").is_not_null())
    if valid.is_empty():
        return valid
    mode_locator = valid.group_by("locator").len().sort("len", descending=True)["locator"][0]
    return calibrated.filter(pl.col("locator") != mode_locator)


def freeze_table(calibrated: pl.DataFrame) -> Dict[str, tuple]:
    """Aggregate the per-contract calibration into the ``{'TXO': (...)}`` table.

    Every contract must agree on one locator, or the table comes back empty
    (``docs/pages/txo.md`` §9's ``unproven`` -- never a guessed constant).
    """
    valid = calibrated.filter(pl.col("locator").is_not_null())
    if valid.is_empty():
        return {}
    locators = set(valid["locator"].to_list())
    if len(locators) != 1:
        return {}
    locator = locators.pop()
    ticks = [t for t in valid["tick_raw"].to_list() if t]
    tick_raw = _gcd_of(ticks) if ticks else None
    tick_1e4 = price_raw_to_1e4(tick_raw, locator) if tick_raw and locator <= 4 else None
    n_steps = int(valid["n_steps"].sum())
    return {"TXO": ("TXO", int(locator), tick_raw, tick_1e4, valid.height, n_steps)}


def render_table_module(table: Dict[str, tuple], version: str, calibration_day: str) -> str:
    """Source text of ``txo_decimal_locator_table.py`` for a frozen table."""
    lines = [
        '"""Frozen TXO decimal-locator table. Generated by',
        'scripts/calibrate_txo_locator.py; do not edit by hand. Query and',
        'semantics: txo_decimal_locator.py."""',
        "",
        f"TXO_DECIMAL_LOCATOR_VERSION = {version!r}",
        f"TXO_DECIMAL_LOCATOR_CALIBRATION_DAY = {calibration_day!r}",
        "",
        "# root: (root, locator, tick_raw, tick_1e4, n_products, n_steps)",
        "TXO_DECIMAL_LOCATOR_TABLE = {",
    ]
    for root, entry in table.items():
        lines.append(f"    {root!r}: {tuple(entry)!r},")
    lines.append("}")
    return "\n".join(lines) + "\n"
