"""Frozen per-product decimal locator and tick for TAIFEX futures prices.

The FOP parquets carry ``price_raw`` (an integer) with no scaling; the true
scale is the product's I010 decimal locator, which the archive does not
hold. This table freezes it, calibrated offline by the query below
(``PLAN_SSF.md`` §8.1) and regenerated by
``scripts/calibrate_ssf_locator.py``:

    Fetch https://openapi.taifex.com.tw/v1/DailyMarketReportFut for a trading
    day (TradingSession == '一般'), join it to
    /mnt/nfs/backup/fop_parquets/futures_day_<YYYYMMDD>_0840_i024.parquet on
    (Contract, ContractMonth) -> prod_id, and for every single-leg product
    print round(log10(Last / max(price_raw))) alongside the gcd of its
    consecutive distinct price_raw values.

Entries are keyed by product root (the first three characters of a
PROD-ID, e.g. ``CDF``; a weekly root such as ``MX4`` is its own key) and
aggregate every delivery month traded on the calibration day. A root whose
months disagree on the locator is left out. A product missing from the
table has no locator: render 「—」 with 「刻度未證實」, never a plausible
guess.

Money stays integral: ``tick_1e4`` and ``price_raw_to_1e4`` are in
1/10000 NTD.
"""

import math
from decimal import Decimal
from typing import Dict, Iterable, NamedTuple, Optional

import polars as pl

from .ssf_decimal_locator_table import (
    SSF_DECIMAL_LOCATOR_CALIBRATION_DAY,
    SSF_DECIMAL_LOCATOR_TABLE,
    SSF_DECIMAL_LOCATOR_VERSION,
)

SSF_DECIMAL_LOCATOR_QUERY = (
    "Fetch https://openapi.taifex.com.tw/v1/DailyMarketReportFut for a trading day "
    "(TradingSession == '一般'), join it to "
    "/mnt/nfs/backup/fop_parquets/futures_day_<YYYYMMDD>_0840_i024.parquet on "
    "(Contract, ContractMonth) -> prod_id, and for every single-leg product print "
    "round(log10(Last / max(price_raw))) alongside the gcd of its consecutive "
    "distinct price_raw values."
)

# TWSE tick ladder in 1/10000 NTD: (price lower bound inclusive, tick).
# This is the assumed ladder the calibration checks each product against.
TWSE_TICK_LADDER_1E4 = (
    (0, 100),              # < 10       : 0.01
    (10_0000, 500),        # 10 - 50    : 0.05
    (50_0000, 1000),       # 50 - 100   : 0.10
    (100_0000, 5000),      # 100 - 500  : 0.50
    (500_0000, 1_0000),    # 500 - 1000 : 1.00
    (1000_0000, 5_0000),   # >= 1000    : 5.00
)


class LocatorEntry(NamedTuple):
    root: str
    locator: int           # price = price_raw / 10**locator
    tick_raw: Optional[int]  # gcd of observed price steps in price_raw units; None if unobserved
    tick_1e4: Optional[int]  # the same step in 1/10000 NTD
    n_products: int        # delivery months the entry aggregates
    n_steps: int           # price changes the gcd was taken over (few = weak evidence)
    ladder_agrees: Optional[bool]  # tick_raw equals the TWSE ladder step at Last


# The gcd of observed steps is a multiple of the true tick: with few price
# changes it can overshoot. Entries with fewer steps than this are frozen
# but flagged so a consumer can treat their tick as unproven.
MIN_STEPS_FOR_TICK = 20


def twse_tick_1e4(price_1e4: int) -> int:
    """TWSE ladder tick (1/10000 NTD) for a price in 1/10000 NTD."""
    tick = TWSE_TICK_LADDER_1E4[0][1]
    for lower, step in TWSE_TICK_LADDER_1E4:
        if price_1e4 >= lower:
            tick = step
    return tick


def price_raw_to_1e4(price_raw: int, locator: int) -> int:
    """Rescale a raw exchange integer to 1/10000 NTD without touching floats."""
    if locator > 4:
        raise ValueError(f"locator {locator} exceeds the 1/10000 NTD resolution")
    return int(price_raw) * 10 ** (4 - locator)


def decimal_to_1e4(text: str) -> int:
    """``'2380'`` / ``'3618.4'`` -> integer 1/10000 NTD, exact."""
    return int((Decimal(text) * 10_000).to_integral_value())


def get_ssf_decimal_locator(prod_id_or_root: str) -> Optional[LocatorEntry]:
    """Frozen entry for a PROD-ID (``CDFI6``) or root (``CDF``); None if absent."""
    entry = SSF_DECIMAL_LOCATOR_TABLE.get(prod_id_or_root[:3])
    if entry is None:
        return None
    return LocatorEntry(*entry)


def ssf_decimal_locator_version() -> str:
    return SSF_DECIMAL_LOCATOR_VERSION


def ssf_decimal_locator_calibration_day() -> str:
    return SSF_DECIMAL_LOCATOR_CALIBRATION_DAY


# ----------------------------------------------------------------------
# Calibration (the §8.1 query as code; used by scripts/calibrate_ssf_locator.py)
# ----------------------------------------------------------------------

def _gcd_of(values: Iterable[int]) -> int:
    out = 0
    for v in values:
        out = math.gcd(out, int(v))
    return out


def observed_ticks(i024: pl.LazyFrame) -> pl.DataFrame:
    """Per single-leg prod_id: ``max_price_raw``, ``tick_raw``, ``n_steps`` from i024.

    Deals are ordered by (prod_msg_seq, match_index); trial matches
    (``calculated_flag == '1'``) are excluded; ``tick_raw`` is the gcd of the
    absolute differences between consecutive distinct prices (0 when the
    product printed a single price all day) and ``n_steps`` how many such
    differences there were.
    """
    per_product = (
        i024.filter(
            ~pl.col("prod_id").str.contains("/", literal=True)
            & (pl.col("calculated_flag") != "1")
        )
        .select("prod_id", "prod_msg_seq", "match_index", "price_raw")
        .sort(["prod_id", "prod_msg_seq", "match_index"])
        .group_by("prod_id", maintain_order=True)
        .agg(
            pl.col("price_raw").cast(pl.Int64).max().alias("max_price_raw"),
            pl.col("price_raw")
            .cast(pl.Int64)
            .diff()
            .abs()
            .filter(pl.col("price_raw").cast(pl.Int64).diff().abs() > 0)
            .alias("steps"),
        )
        .collect()
    )
    steps = per_product["steps"].to_list()
    return per_product.drop("steps").with_columns(
        pl.Series("tick_raw", [_gcd_of(s) for s in steps], dtype=pl.Int64),
        pl.Series("n_steps", [len(s) for s in steps], dtype=pl.Int64),
    )


def calibrate_locator(report, i024: pl.LazyFrame) -> pl.DataFrame:
    """The §8.1 query: one row per single-leg product traded that day.

    ``report`` is ``TaifexWrapper.get_daily_market_report_fut(day)`` (pandas,
    ``一般`` session, with ``prod_id``); ``i024`` the day's futures i024
    scan. Columns: prod_id, contract, contract_month, last, max_price_raw,
    locator, tick_raw, n_steps, ladder_tick_raw, agrees.

    ``locator = -round(log10(Last / max_price_raw))``; ``ladder_tick_raw`` is
    the TWSE ladder step at ``Last`` expressed in price_raw units under that
    locator; ``agrees`` is null when the product printed a single price.
    """
    rep = pl.from_pandas(
        report[["prod_id", "Contract", "ContractMonth(Week)", "Last"]].rename(
            columns={"Contract": "contract", "ContractMonth(Week)": "contract_month", "Last": "last"}
        )
    ).filter(pl.col("prod_id").is_not_null())
    joined = observed_ticks(i024).join(rep, on="prod_id", how="inner")

    def locator_of(last: str, max_raw: int) -> Optional[int]:
        try:
            value = float(last)
        except (TypeError, ValueError):
            return None
        if value <= 0 or max_raw <= 0:
            return None
        return -round(math.log10(value / max_raw))

    def ladder_tick_raw(last: str, locator: Optional[int]) -> Optional[int]:
        if locator is None or locator > 4:
            return None
        tick_1e4 = twse_tick_1e4(decimal_to_1e4(last))
        unit = 10 ** (4 - locator)
        return tick_1e4 // unit if tick_1e4 % unit == 0 else None

    locators = [locator_of(l, m) for l, m in zip(joined["last"], joined["max_price_raw"])]
    ladder = [ladder_tick_raw(l, loc) for l, loc in zip(joined["last"], locators)]
    out = joined.with_columns(
        pl.Series("locator", locators, dtype=pl.Int64),
        pl.Series("ladder_tick_raw", ladder, dtype=pl.Int64),
    ).with_columns(
        pl.when(pl.col("tick_raw") > 0)
        .then(pl.col("tick_raw") == pl.col("ladder_tick_raw"))
        .otherwise(None)
        .alias("agrees")
    )
    return out.select(
        "prod_id", "contract", "contract_month", "last", "max_price_raw",
        "locator", "tick_raw", "n_steps", "ladder_tick_raw", "agrees",
    ).sort("prod_id")


def disagreements(calibrated: pl.DataFrame) -> pl.DataFrame:
    """Products whose locator is not 2 or whose observed tick is off the ladder."""
    return calibrated.filter(
        (pl.col("locator") != 2) | (pl.col("agrees") == False)  # noqa: E712 (polars expr)
    )


def freeze_table(calibrated: pl.DataFrame) -> Dict[str, tuple]:
    """Aggregate the per-product calibration into the per-root frozen table.

    A root's months must agree on the locator, or the root is left out. The
    root's tick is the gcd of its months' observed ticks (months that printed
    one price contribute nothing); ``ladder_agrees`` is True only when every
    month with an observed tick sits on the ladder.
    """
    table: Dict[str, tuple] = {}
    with_root = calibrated.filter(pl.col("locator").is_not_null()).with_columns(
        pl.col("prod_id").str.slice(0, 3).alias("root")
    )
    for root, group in with_root.group_by("root", maintain_order=True):
        root = root[0]
        locators = set(group["locator"].to_list())
        if len(locators) != 1:
            continue
        locator = locators.pop()
        ticks = [t for t in group["tick_raw"].to_list() if t]
        tick_raw = _gcd_of(ticks) if ticks else None
        tick_1e4 = price_raw_to_1e4(tick_raw, locator) if tick_raw and locator <= 4 else None
        n_steps = int(group["n_steps"].sum())
        agrees_values = [a for a in group["agrees"].to_list() if a is not None]
        ladder_agrees = all(agrees_values) if agrees_values else None
        table[root] = (root, int(locator), tick_raw, tick_1e4, group.height, n_steps, ladder_agrees)
    return dict(sorted(table.items()))


def render_table_module(table: Dict[str, tuple], version: str, calibration_day: str) -> str:
    """Source text of ``ssf_decimal_locator_table.py`` for a frozen table."""
    lines = [
        '"""Frozen SSF decimal-locator table. Generated by scripts/calibrate_ssf_locator.py;',
        "do not edit by hand. Query and semantics: ssf_decimal_locator.py.\"\"\"",
        "",
        f"SSF_DECIMAL_LOCATOR_VERSION = {version!r}",
        f"SSF_DECIMAL_LOCATOR_CALIBRATION_DAY = {calibration_day!r}",
        "",
        "# root: (root, locator, tick_raw, tick_1e4, n_products, n_steps, ladder_agrees)",
        "SSF_DECIMAL_LOCATOR_TABLE = {",
    ]
    for root, entry in table.items():
        lines.append(f"    {root!r}: {tuple(entry)!r},")
    lines.append("}")
    return "\n".join(lines) + "\n"
